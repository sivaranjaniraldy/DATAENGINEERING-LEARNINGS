"""2.Using the employee DataFrame, partition by Department and order by Salary descending. Demonstrate rank(), dense_rank(), row_number(), and ntile(3). Explain the difference between them."""

from pyspark.sql import SparkSession
from pyspark.sql.window import Window
from pyspark.sql.functions import rank, dense_rank, row_number, ntile

spark = SparkSession.builder \
    .appName("WindowFunctions") \
    .master("local[*]") \
    .getOrCreate()

# Window Specification
windowSpec = Window.partitionBy("Department").orderBy(df.Salary.desc())

result = df.withColumn("Rank", rank().over(windowSpec)) \
           .withColumn("DenseRank", dense_rank().over(windowSpec)) \
           .withColumn("RowNumber", row_number().over(windowSpec)) \
           .withColumn("NTile", ntile(3).over(windowSpec))

result.show()

