"""4.Using a window ordered by JoinDate, compute a running total of salaries (running_salary_total) so that each row contains the cumulative salary up to that employee. Explain how the window frame works."""

from pyspark.sql import SparkSession
from pyspark.sql.window import Window
from pyspark.sql.functions import sum

# Create Spark Session
spark = SparkSession.builder \
    .appName("RunningTotal") \
    .master("local[*]") \
    .getOrCreate()

# Window Specification
windowSpec = Window.orderBy("JoinDate") \
                   .rowsBetween(Window.unboundedPreceding, Window.currentRow)

# Running Total
result = df.withColumn(
    "RunningSalaryTotal",
    sum("Salary").over(windowSpec)
)

print("Running Total of Salary")
result.show()

