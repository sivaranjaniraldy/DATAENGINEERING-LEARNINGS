"""**4. Find the largest element in an array**"""

arr = list(map(int, input("Enter numbers separated by space: ").split()))

largest = arr[0]

for i in arr:
    if i > largest:
        largest = i

print("Largest element:", largest)

"""**5. Find the second largest number in an array**"""

arr = list(map(int, input("Enter numbers separated by space: ").split()))

largest = second = float('-inf')

for i in arr:
    if i > largest:
        second = largest
        largest = i
    elif i > second and i != largest:
        second = i

print("Second largest element:", second)

"""**6. Remove duplicate elements from an array**"""

arr = list(map(int, input("Enter numbers separated by space: ").split()))

result = []

for i in arr:
    if i not in result:
        result.append(i)

print("Array after removing duplicates:", result)

