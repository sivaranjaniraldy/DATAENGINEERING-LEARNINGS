"""**10. Sort an array without using sort()**"""

arr = list(map(int, input("Enter numbers separated by space: ").split()))

for i in range(len(arr)):
    for j in range(i + 1, len(arr)):
        if arr[i] > arr[j]:
            arr[i], arr[j] = arr[j], arr[i]

print("Sorted array:", arr)